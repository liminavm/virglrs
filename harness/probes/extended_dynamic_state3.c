static uint32_t mem_type(VkPhysicalDevice pd, uint32_t bits, VkMemoryPropertyFlags want) {
    VkPhysicalDeviceMemoryProperties mp;
    vkGetPhysicalDeviceMemoryProperties(pd, &mp);
    for (uint32_t i = 0; i < mp.memoryTypeCount; i++) {
        if ((bits & (1u << i)) && (mp.memoryTypes[i].propertyFlags & want) == want) {
            return i;
        }
    }
    return UINT32_MAX;
}

static VkDeviceMemory bind(VkPhysicalDevice pd, VkDevice dev, VkMemoryRequirements mr,
                           VkMemoryPropertyFlags want) {
    uint32_t type = mem_type(pd, mr.memoryTypeBits, want);
    if (type == UINT32_MAX) {
        fatal("no memory type with the wanted properties", VK_ERROR_INITIALIZATION_FAILED);
    }
    VkMemoryAllocateInfo mai = {
        .sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO,
        .allocationSize = mr.size,
        .memoryTypeIndex = type,
    };
    VkDeviceMemory mem;
    VkResult r = vkAllocateMemory(dev, &mai, NULL, &mem);
    if (r != VK_SUCCESS) {
        fatal("vkAllocateMemory", r);
    }
    return mem;
}

struct mapped {
    VkBuffer buf;
    VkDeviceMemory mem;
    uint8_t *p;
};

static struct mapped mapped(VkPhysicalDevice pd, VkDevice dev, VkDeviceSize size) {
    struct mapped m;
    VkResult r;
    VkBufferCreateInfo bci = {
        .sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO,
        .size = size,
        .usage = VK_BUFFER_USAGE_TRANSFER_DST_BIT,
        .sharingMode = VK_SHARING_MODE_EXCLUSIVE,
    };
    if ((r = vkCreateBuffer(dev, &bci, NULL, &m.buf)) != VK_SUCCESS) {
        fatal("vkCreateBuffer", r);
    }
    VkMemoryRequirements mr;
    vkGetBufferMemoryRequirements(dev, m.buf, &mr);
    m.mem = bind(pd, dev, mr,
                 VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
    vkBindBufferMemory(dev, m.buf, m.mem, 0);
    if ((r = vkMapMemory(dev, m.mem, 0, VK_WHOLE_SIZE, 0, (void **)&m.p)) != VK_SUCCESS) {
        fatal("vkMapMemory", r);
    }
    memset(m.p, 0xee, size);
    return m;
}

struct target {
    VkImage image;
    VkImageView view;
    VkDeviceMemory mem;
};

// Everything the renders share: the device, the one command buffer they are all recorded into,
// the buffer every image is copied out to, and the images, for cleanup.
struct probe {
    VkPhysicalDevice pd;
    VkDevice dev;
    VkCommandBuffer cb;
    struct mapped out;
    VkDeviceSize cursor;
    struct target targets[MAX_TARGETS];
    int ntargets;
};

static struct target *target(struct probe *p, VkFormat format, uint32_t w, uint32_t h,
                             VkSampleCountFlagBits samples, VkImageUsageFlags usage,
                             VkImageAspectFlags aspect) {
    if (p->ntargets == MAX_TARGETS) {
        fatal("too many targets", VK_ERROR_OUT_OF_HOST_MEMORY);
    }
    struct target *t = &p->targets[p->ntargets++];
    VkResult r;
    VkImageCreateInfo ici = {
        .sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO,
        .imageType = VK_IMAGE_TYPE_2D,
        .format = format,
        .extent = {w, h, 1},
        .mipLevels = 1,
        .arrayLayers = 1,
        .samples = samples,
        .tiling = VK_IMAGE_TILING_OPTIMAL,
        .usage = usage | (samples == VK_SAMPLE_COUNT_1_BIT ? VK_IMAGE_USAGE_TRANSFER_SRC_BIT : 0),
        .initialLayout = VK_IMAGE_LAYOUT_UNDEFINED,
    };
    if ((r = vkCreateImage(p->dev, &ici, NULL, &t->image)) != VK_SUCCESS) {
        fatal("vkCreateImage", r);
    }
    VkMemoryRequirements mr;
    vkGetImageMemoryRequirements(p->dev, t->image, &mr);
    t->mem = bind(p->pd, p->dev, mr, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    vkBindImageMemory(p->dev, t->image, t->mem, 0);
    VkImageViewCreateInfo vci = {
        .sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO,
        .image = t->image,
        .viewType = VK_IMAGE_VIEW_TYPE_2D,
        .format = format,
        .subresourceRange = {aspect, 0, 1, 0, 1},
    };
    if ((r = vkCreateImageView(p->dev, &vci, NULL, &t->view)) != VK_SUCCESS) {
        fatal("vkCreateImageView", r);
    }
    return t;
}

static void to_layout(VkCommandBuffer cb, VkImage image, VkImageAspectFlags aspect,
                      VkImageLayout from, VkImageLayout to) {
    VkImageMemoryBarrier b = {
        .sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER,
        .srcAccessMask = VK_ACCESS_MEMORY_WRITE_BIT,
        .dstAccessMask = VK_ACCESS_MEMORY_READ_BIT | VK_ACCESS_MEMORY_WRITE_BIT,
        .oldLayout = from,
        .newLayout = to,
        .srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED,
        .dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED,
        .image = image,
        .subresourceRange = {aspect, 0, 1, 0, 1},
    };
    vkCmdPipelineBarrier(cb, VK_PIPELINE_STAGE_ALL_COMMANDS_BIT,
                         VK_PIPELINE_STAGE_ALL_COMMANDS_BIT, 0, 0, NULL, 0, NULL, 1, &b);
}

// One render pass instance: its images, and where each lands in the readback buffer.
struct render {
    uint32_t w, h, colors;
    VkSampleCountFlagBits samples;
    int depth;
    struct target *color[2], *msaa, *zbuf;
    VkDeviceSize color_at[2], depth_at;
};

// Begins rendering into fresh images: `colors` RGBA8 attachments cleared to `clear`, a D32
// attachment cleared to 1.0 if `depth`, and for more than one sample a multisampled colour
// attachment resolved by averaging into the single-sampled one.
static struct render begin(struct probe *p, uint32_t w, uint32_t h, uint32_t colors,
                           VkSampleCountFlagBits samples, int depth, const float clear[2][4]) {
    const VkImageAspectFlags C = VK_IMAGE_ASPECT_COLOR_BIT, D = VK_IMAGE_ASPECT_DEPTH_BIT;
    const VkImageLayout ATT = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
    struct render r = {.w = w, .h = h, .colors = colors, .samples = samples, .depth = depth};
    VkRenderingAttachmentInfo att[2];
    for (uint32_t a = 0; a < colors; a++) {
        r.color[a] = target(p, VK_FORMAT_R8G8B8A8_UNORM, w, h, VK_SAMPLE_COUNT_1_BIT,
                            VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT, C);
        to_layout(p->cb, r.color[a]->image, C, VK_IMAGE_LAYOUT_UNDEFINED, ATT);
        att[a] = (VkRenderingAttachmentInfo){
            .sType = VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO,
            .imageView = r.color[a]->view,
            .imageLayout = ATT,
            .loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR,
            .storeOp = VK_ATTACHMENT_STORE_OP_STORE,
        };
        memcpy(att[a].clearValue.color.float32, clear[a], sizeof clear[a]);
    }
    if (samples != VK_SAMPLE_COUNT_1_BIT) {
        r.msaa = target(p, VK_FORMAT_R8G8B8A8_UNORM, w, h, samples,
                        VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT, C);
        to_layout(p->cb, r.msaa->image, C, VK_IMAGE_LAYOUT_UNDEFINED, ATT);
        att[0].imageView = r.msaa->view;
        att[0].storeOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
        att[0].resolveMode = VK_RESOLVE_MODE_AVERAGE_BIT;
        att[0].resolveImageView = r.color[0]->view;
        att[0].resolveImageLayout = ATT;
    }
    VkRenderingAttachmentInfo zatt;
    if (depth) {
        r.zbuf = target(p, VK_FORMAT_D32_SFLOAT, w, h, VK_SAMPLE_COUNT_1_BIT,
                        VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT, D);
        to_layout(p->cb, r.zbuf->image, D, VK_IMAGE_LAYOUT_UNDEFINED,
                  VK_IMAGE_LAYOUT_DEPTH_ATTACHMENT_OPTIMAL);
        zatt = (VkRenderingAttachmentInfo){
            .sType = VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO,
            .imageView = r.zbuf->view,
            .imageLayout = VK_IMAGE_LAYOUT_DEPTH_ATTACHMENT_OPTIMAL,
            .loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR,
            .storeOp = VK_ATTACHMENT_STORE_OP_STORE,
            .clearValue = {.depthStencil = {1.0f, 0}},
        };
    }
    VkRenderingInfo ri = {
        .sType = VK_STRUCTURE_TYPE_RENDERING_INFO,
        .renderArea = {{0, 0}, {w, h}},
        .layerCount = 1,
        .colorAttachmentCount = colors,
        .pColorAttachments = att,
        .pDepthAttachment = depth ? &zatt : NULL,
    };
    vkCmdBeginRendering(p->cb, &ri);
    return r;
}

static void copy_out(struct probe *p, struct target *t, VkImageAspectFlags aspect,
                     VkImageLayout from, uint32_t w, uint32_t h, VkDeviceSize *at) {
    to_layout(p->cb, t->image, aspect, from, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL);
    *at = p->cursor;
    p->cursor += (VkDeviceSize)w * h * 4;
    if (p->cursor > READBACK_SIZE) {
        fatal("readback buffer too small", VK_ERROR_OUT_OF_DEVICE_MEMORY);
    }
    VkBufferImageCopy copy = {
        .bufferOffset = *at,
        .imageSubresource = {aspect, 0, 0, 1},
        .imageExtent = {w, h, 1},
    };
    vkCmdCopyImageToBuffer(p->cb, t->image, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, p->out.buf, 1,
                           &copy);
}

static void end(struct probe *p, struct render *r) {
    vkCmdEndRendering(p->cb);
    for (uint32_t a = 0; a < r->colors; a++) {
        copy_out(p, r->color[a], VK_IMAGE_ASPECT_COLOR_BIT,
                 VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, r->w, r->h, &r->color_at[a]);
    }
    if (r->depth) {
        copy_out(p, r->zbuf, VK_IMAGE_ASPECT_DEPTH_BIT, VK_IMAGE_LAYOUT_DEPTH_ATTACHMENT_OPTIMAL,
                 r->w, r->h, &r->depth_at);
    }
}

// Every state a draw here depends on. `state()` gives the baseline; a render changes only what
// it is about.
struct state {
    uint32_t w, h, colors;
    float min_depth, max_depth;
    VkTessellationDomainOrigin origin;
    VkBool32 clamp, clip, n1to1, a2c, a2o, logic, sloc, stipple;
    VkPolygonMode polygon;
    VkSampleCountFlagBits samples;
    VkSampleMask sample_mask;
    VkBool32 blend[2];
    VkColorBlendEquationEXT eq[2];
    VkColorComponentFlags mask[2];
    VkProvokingVertexModeEXT pv;
    VkConservativeRasterizationModeEXT conserv;
    VkLineRasterizationModeEXT linemode;
};

static struct state state(uint32_t w, uint32_t h, uint32_t colors) {
    const VkColorBlendEquationEXT replace = {
        VK_BLEND_FACTOR_ONE, VK_BLEND_FACTOR_ZERO, VK_BLEND_OP_ADD,
        VK_BLEND_FACTOR_ONE, VK_BLEND_FACTOR_ZERO, VK_BLEND_OP_ADD,
    };
    const VkColorComponentFlags rgba = VK_COLOR_COMPONENT_R_BIT | VK_COLOR_COMPONENT_G_BIT |
                                       VK_COLOR_COMPONENT_B_BIT | VK_COLOR_COMPONENT_A_BIT;
    return (struct state){
        .w = w,
        .h = h,
        .colors = colors,
        .max_depth = 1.0f,
        .origin = VK_TESSELLATION_DOMAIN_ORIGIN_UPPER_LEFT,
        .clip = VK_TRUE,
        .polygon = VK_POLYGON_MODE_FILL,
        .samples = VK_SAMPLE_COUNT_1_BIT,
        .sample_mask = ~0u,
        .eq = {replace, replace},
        .mask = {rgba, rgba},
        .pv = VK_PROVOKING_VERTEX_MODE_FIRST_VERTEX_EXT,
        .conserv = VK_CONSERVATIVE_RASTERIZATION_MODE_DISABLED_EXT,
        .linemode = VK_LINE_RASTERIZATION_MODE_DEFAULT_EXT,
    };
}

// Sets every state the bound pipeline declares dynamic. Binding a pipeline invalidates what it
// declares static, so this follows every bind. The per-attachment states go one attachment per
// call, so attachment 1 is always set with firstAttachment = 1.
static void apply(VkCommandBuffer cb, const struct state *s) {
    VkViewport vp = {0, 0, (float)s->w, (float)s->h, s->min_depth, s->max_depth};
    VkRect2D sc = {{0, 0}, {s->w, s->h}};
    vkCmdSetViewport(cb, 0, 1, &vp);
    vkCmdSetScissor(cb, 0, 1, &sc);
    if (usable[TDO]) fn.tdo(cb, s->origin);
    if (usable[CLAMP]) fn.clamp(cb, s->clamp);
    if (usable[POLY]) fn.poly(cb, s->polygon);
    if (usable[RSAMPLES]) fn.rsamples(cb, s->samples);
    if (usable[SMASK]) fn.smask(cb, s->samples, &s->sample_mask);
    if (usable[A2C]) fn.a2c(cb, s->a2c);
    if (usable[A2O]) fn.a2o(cb, s->a2o);
    if (usable[LOGIC]) fn.logic(cb, s->logic);
    for (uint32_t a = 0; a < s->colors; a++) {
        if (usable[BLEND_EN]) fn.blend_en(cb, a, 1, &s->blend[a]);
        if (usable[BLEND_EQ]) fn.blend_eq(cb, a, 1, &s->eq[a]);
        if (usable[WMASK]) fn.wmask(cb, a, 1, &s->mask[a]);
    }
    if (usable[RSTREAM]) fn.rstream(cb, 0);
    if (usable[CONSERV]) fn.conserv(cb, s->conserv);
    if (usable[EXTRA]) fn.extra(cb, 0.0f);
    if (usable[CLIP]) fn.clip(cb, s->clip);
    if (usable[SLOC]) fn.sloc(cb, s->sloc);
    if (usable[PV]) fn.pv(cb, s->pv);
    if (usable[LINEMODE]) fn.linemode(cb, s->linemode);
    if (usable[STIPPLE_EN]) fn.stipple_en(cb, s->stipple);
    if (usable[N1TO1]) fn.n1to1(cb, s->n1to1);
}

