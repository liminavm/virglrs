// The `extended-dynamic-state3` group of src/venus/unserved.txt, as a program that names each
// command.
//
//   vkCmdSetTessellationDomainOriginEXT        vkCmdSetDepthClampEnableEXT
//   vkCmdSetPolygonModeEXT                     vkCmdSetRasterizationSamplesEXT
//   vkCmdSetSampleMaskEXT                      vkCmdSetAlphaToCoverageEnableEXT
//   vkCmdSetAlphaToOneEnableEXT                vkCmdSetLogicOpEnableEXT
//   vkCmdSetColorBlendEnableEXT                vkCmdSetColorBlendEquationEXT
//   vkCmdSetColorWriteMaskEXT                  vkCmdSetRasterizationStreamEXT
//   vkCmdSetConservativeRasterizationModeEXT   vkCmdSetExtraPrimitiveOverestimationSizeEXT
//   vkCmdSetDepthClipEnableEXT                 vkCmdSetSampleLocationsEnableEXT
//   vkCmdSetColorBlendAdvancedEXT              vkCmdSetProvokingVertexModeEXT
//   vkCmdSetLineRasterizationModeEXT           vkCmdSetLineStippleEnableEXT
//   vkCmdSetDepthClipNegativeOneToOneEXT
//
// From VK_EXT_extended_dynamic_state3, where every command has a feature bit of its own and the
// hosts offer very different subsets: KosmicKrisp five of them, anv nineteen. The probe enables
// every one the device offers -- with the feature or extension its values need -- and prints
// each of the others as skipped, which is not a failure. Every pipeline declares exactly the
// states that are on, and every draw sets all of them after the bind.
//
// Every render goes into fresh RGBA8 (and D32) images that are copied out and read back:
//
//   - DepthClampEnable, DepthClipEnable: a fullscreen triangle at z = 1.5 through a viewport of
//     depth range [0, 0.5]. Clamp on, clip off: depth 0.5. Clamp off, clip off: 0.75, unclamped.
//     Clip on: nothing drawn. Where clip is not dynamic it follows !clamp, so clamp off draws
//     nothing there.
//   - DepthClipNegativeOneToOne: the triangle at z = -0.5. Off, it is outside [0, 1] and
//     clipped; on, it lands at depth 0.25.
//   - ColorWriteMask: two attachments, all ones written; RGBA on attachment 0, R|A on
//     attachment 1 set with firstAttachment = 1.
//   - ColorBlendEnable, ColorBlendEquation: 0.25 onto a 0.5 clear. Attachment 0 unblended reads
//     0.25; attachment 1, enabled and given ONE/ONE ADD for colour and ZERO/ONE for alpha with
//     firstAttachment = 1, reads 0.75 and keeps alpha 0.5.
//   - LogicOpEnable: a static XOR, 0x0f onto 0xf0: off reads 0x0f, on 0xff.
//   - PolygonMode: a triangle with an edge inside the target. LINE lights fewer pixels than FILL.
//   - ConservativeRasterizationMode: the same triangle overestimated lights more than FILL.
//   - ProvokingVertexMode: a flat varying of the vertex index. FIRST reads vertex 0's value,
//     LAST vertex 2's.
//   - RasterizationSamples, SampleMask, AlphaToCoverageEnable, AlphaToOneEnable: a 4x target
//     resolved by averaging. The pipeline is built for one sample where the count is dynamic,
//     so only the command makes it four. Four samples leave partially covered pixels along a
//     diagonal edge; a mask of two samples halves a white fill; alpha 0.5 with coverage from
//     alpha halves it too; alpha to one turns a written alpha of 0.5 into 1.
//   - TessellationDomainOrigin: one tessellated triangle, back faces culled. The origin flips
//     the winding of the generated triangle, so one origin fills the target and the other draws
//     nothing.
//   - LineStippleEnable: a Bresenham line across 16x1 with pattern 0x0f0f at factor 2. Off
//     lights all 16 pixels, on lights 0..7 only.
//
// Scored by the renderer log only, recorded in the submitted command buffer where offered:
// vkCmdSetRasterizationStreamEXT (stream 0 is the only one either host can rasterize),
// vkCmdSetSampleLocationsEnableEXT, vkCmdSetLineRasterizationModeEXT,
// vkCmdSetExtraPrimitiveOverestimationSizeEXT and vkCmdSetColorBlendAdvancedEXT.
//
// The shaders, compiled with `glslangValidator -V --target-env vulkan1.1 -x`:
//
//   // main.vert
//   #version 450
//   layout(push_constant) uniform PC { vec4 c0; vec4 c1; float scale; float z; int usepv; } pc;
//   layout(location = 0) flat out int pv;
//   void main() {
//       vec2 p = vec2((gl_VertexIndex << 1) & 2, gl_VertexIndex & 2);
//       gl_Position = vec4((p * 2.0 - 1.0) * pc.scale, pc.z, 1.0);
//       pv = gl_VertexIndex;
//   }
//
//   // main.frag
//   #version 450
//   layout(push_constant) uniform PC { vec4 c0; vec4 c1; float scale; float z; int usepv; } pc;
//   layout(location = 0) flat in int pv;
//   layout(location = 0) out vec4 a;
//   layout(location = 1) out vec4 b;
//   void main() {
//       a = pc.usepv != 0 ? vec4(float(pv + 1) * 0.25, 0.0, 0.0, 1.0) : pc.c0;
//       b = pc.c1;
//   }
//
//   // line.vert
//   #version 450
//   layout(location = 0) flat out int pv;
//   void main() {
//       gl_Position = vec4(gl_VertexIndex == 0 ? -1.0 : 1.0, 0.0, 0.0, 1.0);
//       pv = 0;
//   }
//
//   // patch.vert
//   #version 450
//   void main() {
//       vec2 p = vec2((gl_VertexIndex << 1) & 2, gl_VertexIndex & 2);
//       gl_Position = vec4(p * 2.0 - 1.0, 0.5, 1.0);
//   }
//
//   // patch.tesc
//   #version 450
//   layout(vertices = 3) out;
//   void main() {
//       gl_out[gl_InvocationID].gl_Position = gl_in[gl_InvocationID].gl_Position;
//       gl_TessLevelOuter[0] = 1.0;
//       gl_TessLevelOuter[1] = 1.0;
//       gl_TessLevelOuter[2] = 1.0;
//       gl_TessLevelInner[0] = 1.0;
//   }
//
//   // patch.tese
//   #version 450
//   layout(triangles, equal_spacing, ccw) in;
//   layout(location = 0) flat out int pv;
//   void main() {
//       gl_Position = gl_TessCoord.x * gl_in[0].gl_Position + gl_TessCoord.y * gl_in[1].gl_Position +
//                     gl_TessCoord.z * gl_in[2].gl_Position;
//       pv = 0;
//   }
//
// Headless on purpose: no surface, no swapchain, no window. It runs over ssh.
//
//   cc -O1 -o extended_dynamic_state3 extended_dynamic_state3.c -lvulkan && ./extended_dynamic_state3
//
// Exit 0 = every check passed. Exit 1 = a check failed, and the line above it says which.
// Exit 2 = the device could not be brought up at all (not a verdict on the group).

